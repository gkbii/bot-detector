// `npm run registry` -- renders server/registry/ into docs/registry.md and
// .env.example. Both are committed, and test/registry.test.js re-renders them
// in memory and fails if what is on disk differs, so a registry edit that was
// not rendered is a red suite rather than a stale document.
//
// Run with `--check` to do only that comparison, which is what the test calls.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ENV, ROUTES, EVENTS, ERRORS, commands } from '../server/registry/index.ts';

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * A markdown table cell: newlines and pipes would break the row.
 * @param {unknown} text
 */
function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\n+/g, ' ');
}

function renderRegistryDoc() {
  const out = [];
  out.push('# Registry');
  out.push('');
  out.push('**Generated by `npm run registry` from `server/registry/`. Do not edit by hand** --');
  out.push('`npm test` fails when this file and the registries disagree. Change the registry,');
  out.push('then re-render.');
  out.push('');
  out.push('Every environment variable, HTTP route, worker message, npm script and error code');
  out.push('this repo has. If something is not here, it does not exist.');
  out.push('');

  out.push('## Environment');
  out.push('');
  out.push('Read by the OPTIONAL server only -- the extension reads no environment at all.');
  out.push('`server/config.ts` reads through this list and nothing else.');
  out.push('');
  out.push('| Variable | Default | Description |');
  out.push('| --- | --- | --- |');
  for (const entry of ENV) {
    const def = entry.default === null ? '_(unset)_' : `\`${entry.default}\``;
    out.push(`| \`${entry.key}\` | ${def} | ${cell(entry.description)} |`);
  }
  out.push('');

  out.push('## Routes');
  out.push('');
  out.push('`server/index.ts` dispatches by looking a request up in this table. A path it does');
  out.push('not carry is a 404; one asked with another method is a 405.');
  out.push('');
  out.push('| Method | Path | Description |');
  out.push('| --- | --- | --- |');
  for (const route of ROUTES) {
    out.push(`| \`${route.method}\` | \`${route.path}\` | ${cell(route.description)} |`);
  }
  out.push('');

  out.push('## Worker messages');
  out.push('');
  out.push('The extension’s one internal boundary: content scripts never fetch, they ask the');
  out.push('service worker. Every reply is `{ok: true, data}` or');
  out.push('`{ok: false, error: {message, code, kind}}`.');
  out.push('');
  out.push('| Message | Request | Reply | Description |');
  out.push('| --- | --- | --- | --- |');
  for (const event of EVENTS) {
    out.push(`| \`${event.name}\` | \`${event.request}\` | \`${event.reply}\` | ${cell(event.description)} |`);
  }
  out.push('');

  out.push('## Commands');
  out.push('');
  out.push('Read out of `package.json`, so this list cannot disagree with the scripts it names.');
  out.push('');
  out.push('| Command | Runs |');
  out.push('| --- | --- |');
  for (const command of commands(path.join(repoRoot, 'package.json'))) {
    out.push(`| \`npm run ${command.name}\` | \`${cell(command.run)}\` |`);
  }
  out.push('');

  out.push('## Errors');
  out.push('');
  out.push('From `extension/errors.js`, the one taxonomy. A caller branches on `code`, never on');
  out.push('the message; `status` is what the optional server answers with.');
  out.push('');
  out.push('| Code | Domain | Status | Meaning |');
  out.push('| --- | --- | --- | --- |');
  for (const spec of Object.values(ERRORS)) {
    out.push(`| \`${spec.code}\` | ${spec.domain} | ${spec.httpStatus} | ${cell(spec.summary)} |`);
  }
  out.push('');
  return out.join('\n');
}

function renderEnvExample() {
  const out = [];
  out.push('# bot-detector -- environment for the OPTIONAL server.');
  out.push('#');
  out.push('# GENERATED BY `npm run registry` FROM server/registry/env.ts. Do not edit by hand.');
  out.push('#');
  out.push('# The Chrome extension needs NONE of this: it installs load-unpacked and scores in');
  out.push('# the browser with no account, no key and no server. Copy this to `.env` only if');
  out.push('# you are running the optional backend.');
  out.push('#');
  out.push('# Every value below is the default. Uncomment a line only to change it.');
  for (const entry of ENV) {
    out.push('');
    for (const line of wrapComment(entry.description)) out.push(`# ${line}`);
    if (entry.secret) {
      out.push(`# ${entry.key} IS A SECRET. .env is gitignored; never commit a real value.`);
      out.push(`${entry.key}=`);
    } else {
      out.push(`# ${entry.key}=${entry.default ?? ''}`);
    }
  }
  out.push('');
  return out.join('\n');
}

/**
 * Hard-wrap a description at 76 columns so the file reads in a terminal.
 * @param {string} text
 */
function wrapComment(text) {
  const words = String(text).split(/\s+/);
  const lines = [];
  let line = '';
  for (const word of words) {
    if (line && line.length + 1 + word.length > 76) {
      lines.push(line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(line);
  return lines;
}

/** Path -> rendered text. Exported shape the freshness test reads. */
export function renderAll() {
  return {
    'docs/registry.md': renderRegistryDoc(),
    '.env.example': renderEnvExample(),
  };
}

/**
 * Writes what is stale, or with `--check` only reports it.
 * @param {{ checkOnly: boolean }} opts
 * @returns {number} how many files were stale
 */
function main({ checkOnly }) {
  let stale = 0;
  for (const [relative, text] of Object.entries(renderAll())) {
    const absolute = path.join(repoRoot, relative);
    const current = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : null;
    if (current === text) continue;
    stale += 1;
    if (checkOnly) {
      console.error(`[bot-detector:registry] STALE ${relative} -- run \`npm run registry\``);
    } else {
      fs.mkdirSync(path.dirname(absolute), { recursive: true });
      fs.writeFileSync(absolute, text);
      console.log(`[bot-detector:registry] wrote ${relative}`);
    }
  }
  if (stale === 0) console.log('[bot-detector:registry] up to date');
  return stale;
}

// `npm run registry` renders; IMPORTING this module must do nothing at all.
// test/registry.test.js imports renderAll() to compare against what is on disk,
// and a top-level process.exit() here ends the test run after its first case --
// which it did, silently, reporting 1 passing test instead of 10.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const checkOnly = process.argv.includes('--check');
  process.exit(main({ checkOnly }) > 0 && checkOnly ? 1 : 0);
}
